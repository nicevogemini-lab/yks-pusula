def konulari_uret(ders_kod: str, satirlar: list[tuple]) -> list[dict]:
    """Ham tuple listesini veritabanı sözlüklerine çevirir."""
    sonuc = []
    for i, satir in enumerate(satirlar, start=1):
        ad = satir[0]
        sinif = satir[1] if len(satir) > 1 else 11
        agirlik = satir[2] if len(satir) > 2 else 1
        sure = satir[3] if len(satir) > 3 else 90
        beceri = satir[4] if len(satir) > 4 else ""
        onkosul = satir[5] if len(satir) > 5 else ""
        sonuc.append(
            {
                "kod": f"{ders_kod}-{i:02d}",
                "ders_kod": ders_kod,
                "ad": ad,
                "sinif": sinif,
                "agirlik": agirlik,
                "sure_dk": sure,
                "beceri": beceri,
                "onkosul": onkosul,
                "sira": i,
            }
        )
    return sonuc
